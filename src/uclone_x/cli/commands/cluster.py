def _detect_frontend_bundle() -> InfraComponentStatus:
    """Check that the compiled frontend bundle (`ui_static/index.html` and `assets/`) exists."""
    t0 = time.perf_counter()
    static_dir = Path(__file__).resolve().parents[2] / "ui_static"
    index_ok = (static_dir / "index.html").is_file()
    assets_ok = (static_dir / "assets").is_dir()
    healthy = index_ok and assets_ok
    detail = (
        "Static UI bundle verified (index.html + assets/)"
        if healthy
        else "Missing compiled bundle in ui_static/"
    )
    return InfraComponentStatus(
        name="frontend_bundle",
        endpoint=str(static_dir),
        healthy=healthy,
        latency_ms=round((time.perf_counter() - t0) * 1000.0, 2),
        detail=detail,
    )


def _probe_local_ollama() -> InfraComponentStatus:
    """Probe local Ollama daemon (`127.0.0.1:11434`); optional when cloud/mock models are used."""
    import httpx

    endpoint = "http://127.0.0.1:11434/api/tags"
    t0 = time.perf_counter()
    try:
        resp = httpx.get(endpoint, timeout=1.5)
        if resp.status_code == 200:
            raw = resp.json()
            data = cast(dict[str, Any], raw) if isinstance(raw, dict) else {}
            raw_models = data.get("models")
            models: list[Any] = cast(list[Any], raw_models) if isinstance(raw_models, list) else []
            detail = f"Ollama online ({len(models)} local model(s) available)"
        else:
            detail = f"OPTIONAL (HTTP {resp.status_code}; cloud/mock models available)"
    except Exception:
        detail = "OPTIONAL (offline; cloud/mock models available)"
    return InfraComponentStatus(
        name="local_llm_ollama",
        endpoint="http://127.0.0.1:11434",
        healthy=True,
        latency_ms=round((time.perf_counter() - t0) * 1000.0, 2),
        detail=detail,
    )


def _ensure_ui_daemon_running(
    host: str,
    port: int,
    *,
    cluster_mode: str | None = None,
    wait_seconds: float = 15.0,
) -> InfraComponentStatus:
    """Ensure the Web UI server is running on `host:port` with the desired `cluster_mode`."""
    import httpx

    base_url = f"http://{host}:{port}"
    target_mode = cluster_mode if cluster_mode is not None else "standalone"
    t0 = time.perf_counter()

    def _probe_health() -> dict[str, Any] | None:
        try:
            resp = httpx.get(f"{base_url}/api/health", timeout=1.5)
            if resp.status_code == 200:
                body = resp.json()
                if isinstance(body, dict):
                    return cast(dict[str, Any], body)
        except Exception:
            return None
        return None

    existing = _probe_health()
    if existing is not None:
        active_mode = str(existing.get("cluster_mode", "standalone"))
        if active_mode == target_mode:
            rec = None
            with contextlib.suppress(Exception):
                rec = ui_process.read_dashboard_record(port)
            pid_info = f", pid={rec.pid}" if rec is not None else ""
            return InfraComponentStatus(
                name="web_ui_server",
                endpoint=base_url,
                healthy=True,
                latency_ms=round((time.perf_counter() - t0) * 1000.0, 2),
                detail=f"Already running (cluster_mode={active_mode}{pid_info})",
            )
        with contextlib.suppress(Exception):
            ui_process.stop_ui_server(port=port)

    env = os.environ.copy()
    if cluster_mode is not None:
        env["UCLONE_CLUSTER_MODE"] = cluster_mode
        env[STACK_ENV_FILE_VAR] = str(_stack_env_file())
    else:
        env.pop("UCLONE_CLUSTER_MODE", None)

    proc = subprocess.Popen(
        [sys.executable, "-m", "uclone_x.cli.main", "ui", "--port", str(port), "--host", host],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        stdin=subprocess.DEVNULL,
        start_new_session=True,
        env=env,
    )

    deadline = time.monotonic() + max(1.0, wait_seconds)
    while time.monotonic() < deadline:
        health_data = _probe_health()
        if health_data is not None:
            active_mode = str(health_data.get("cluster_mode", "standalone"))
            return InfraComponentStatus(
                name="web_ui_server",
                endpoint=base_url,
                healthy=True,
                latency_ms=round((time.perf_counter() - t0) * 1000.0, 2),
                detail=f"Started background daemon (pid={proc.pid}, cluster_mode={active_mode})",
            )
        if proc.poll() is not None:
            break
        time.sleep(0.25)

    return InfraComponentStatus(
        name="web_ui_server",
        endpoint=base_url,
        healthy=False,
        latency_ms=round((time.perf_counter() - t0) * 1000.0, 2),
        detail=f"Timed out waiting for Web UI server on {base_url}/api/health",
    )


def _verify_ui_endpoints(
    host: str,
    port: int,
    *,
    cluster_mode: str | None = None,
) -> tuple[InfraComponentStatus, ...]:
    """Run live HTTP verification checks against the active Web UI server on `host:port`."""
    import httpx

    base_url = f"http://{host}:{port}"
    checks: list[InfraComponentStatus] = []

    if cluster_mode is None:
        # Standalone Check 1: Frontend Static Assets
        t0 = time.perf_counter()
        try:
            resp_root = httpx.get(f"{base_url}/", timeout=3.0)
            ok_root = resp_root.status_code == 200 and "<html" in resp_root.text.lower()
            detail_root = (
                f"HTTP 200 HTML ({len(resp_root.text)} bytes)"
                if ok_root
                else f"Unexpected root response: HTTP {resp_root.status_code}"
            )
        except Exception as exc:
            ok_root = False
            detail_root = str(exc)
        checks.append(
            InfraComponentStatus(
                name="1. Frontend Static Assets (/)",
                endpoint=f"{base_url}/",
                healthy=ok_root,
                latency_ms=round((time.perf_counter() - t0) * 1000.0, 2),
                detail=detail_root,
            )
        )

        # Standalone Check 2: Web UI Health & Diagnostics (/api/health)
        t0 = time.perf_counter()
        try:
            resp_h = httpx.get(f"{base_url}/api/health", timeout=3.0)
            raw_h: Any = resp_h.json() if resp_h.status_code == 200 else None
            data_h: dict[str, Any] = cast(dict[str, Any], raw_h) if isinstance(raw_h, dict) else {}
            status_val = str(data_h.get("status", "unknown"))
            mode_val = str(data_h.get("cluster_mode", "standalone"))
            ok_h = resp_h.status_code == 200 and status_val in ("healthy", "degraded")
            detail_h = f"status={status_val}, cluster_mode={mode_val}"
        except Exception as exc:
            ok_h = False
            detail_h = str(exc)
        checks.append(
            InfraComponentStatus(
                name="2. Web UI Health & Diagnostics (/api/health)",
                endpoint=f"{base_url}/api/health",
                healthy=ok_h,
                latency_ms=round((time.perf_counter() - t0) * 1000.0, 2),
                detail=detail_h,
            )
        )

        # Standalone Check 3: Chat Room & Session API (/api/rooms)
        t0 = time.perf_counter()
        try:
            resp_r = httpx.get(f"{base_url}/api/rooms", timeout=3.0)
            raw_r: Any = resp_r.json() if resp_r.status_code == 200 else None
            data_r: dict[str, Any] = cast(dict[str, Any], raw_r) if isinstance(raw_r, dict) else {}
            raw_rooms = data_r.get("rooms")
            rooms: list[Any] | None = (
                cast(list[Any], raw_rooms) if isinstance(raw_rooms, list) else None
            )
            ok_r = resp_r.status_code == 200 and rooms is not None
            detail_r = (
                f"Chat room API ready ({len(rooms)} room(s) listed)"
                if rooms is not None
                else f"HTTP {resp_r.status_code}"
            )
        except Exception as exc:
            ok_r = False
            detail_r = str(exc)
        checks.append(
            InfraComponentStatus(
                name="3. Chat Room & Session API (/api/rooms)",
                endpoint=f"{base_url}/api/rooms",
                healthy=ok_r,
                latency_ms=round((time.perf_counter() - t0) * 1000.0, 2),
                detail=detail_r,
            )
        )
        return tuple(checks)

    # Cluster Mode Stage 6: Web UI Server & Cluster Gateway (/api/health, /api/cluster/health)
    t0 = time.perf_counter()
    try:
        resp_h = httpx.get(f"{base_url}/api/health", timeout=3.0)
        resp_ch = httpx.get(f"{base_url}/api/cluster/health", timeout=3.0)
        raw_h = resp_h.json() if resp_h.status_code == 200 else None
        raw_ch: Any = resp_ch.json() if resp_ch.status_code == 200 else None
        data_h = cast(dict[str, Any], raw_h) if isinstance(raw_h, dict) else {}
        data_ch: dict[str, Any] = cast(dict[str, Any], raw_ch) if isinstance(raw_ch, dict) else {}
        ui_mode = str(data_h.get("cluster_mode", "unknown"))
        cluster_ok = bool(data_ch.get("all_healthy"))
        ok_6 = resp_h.status_code == 200 and resp_ch.status_code == 200 and cluster_ok
        detail_6 = f"ui_mode={ui_mode}, cluster_all_healthy={cluster_ok}"
    except Exception as exc:
        ok_6 = False
        detail_6 = str(exc)
    checks.append(
        InfraComponentStatus(
            name="6. Web UI Server & Cluster Gateway (/api/health, /api/cluster/health)",
            endpoint=f"{base_url}/api/cluster/health",
            healthy=ok_6,
            latency_ms=round((time.perf_counter() - t0) * 1000.0, 2),
            detail=detail_6,
        )
    )

    # Cluster Mode Stage 7: Cluster-Backed Web UI Chat Readiness (/api/rooms)
    t0 = time.perf_counter()
    try:
        resp_r = httpx.get(f"{base_url}/api/rooms", timeout=3.0)
        raw_r = resp_r.json() if resp_r.status_code == 200 else None
        data_r = cast(dict[str, Any], raw_r) if isinstance(raw_r, dict) else {}
        raw_rooms = data_r.get("rooms")
        rooms = cast(list[Any], raw_rooms) if isinstance(raw_rooms, list) else None
        ok_7 = resp_r.status_code == 200 and rooms is not None
        detail_7 = (
            f"Cluster-backed room store ready ({len(rooms)} room(s))"
            if rooms is not None
            else f"HTTP {resp_r.status_code}"
        )
    except Exception as exc:
        ok_7 = False
        detail_7 = str(exc)
    checks.append(
        InfraComponentStatus(
            name="7. Cluster-Backed Web UI Chat Readiness (/api/rooms)",
            endpoint=f"{base_url}/api/rooms",
            healthy=ok_7,
            latency_ms=round((time.perf_counter() - t0) * 1000.0, 2),
            detail=detail_7,
        )
    )
    return tuple(checks)


def _start_and_bootstrap_docker_cluster(
    wait_seconds: int = 30,
) -> tuple[ClusterRuntimeStack, ClusterHealthReport]:
    """Generate missing secrets, start the compose topology, create schema and topics."""
    generated = ensure_stack_env(_stack_env_file())
    if generated:
        # stderr: with `--json`, stdout carries only the JSON report.
        Console(stderr=True).print(f"[dim]• Generated stack secrets into {_stack_env_file()}[/dim]")
    completed = subprocess.run(
        _compose("up", "-d", "--wait", *_DOCKER_SERVICES),
        capture_output=True,
        text=True,
        check=False,
    )
    if completed.returncode != 0:
        console.print(
            f"[bold red]✖ Failed to start Docker cluster services:[/bold red]\n"
            f"{completed.stderr.strip() or completed.stdout.strip()}"
        )
        raise typer.Exit(code=1)

    stack = _build_stack()

    async def _wait_and_bootstrap() -> ClusterHealthReport:
        deadline = time.monotonic() + max(1, wait_seconds)
        last_error = ""
        while True:
            try:
                await stack.bootstrap_schema()
                last_error = ""
            except Exception as exc:  # services may still be starting; retried until deadline
                last_error = f"{type(exc).__name__}: {exc}"
            report = await stack.check_health()
            if (report.all_healthy and not last_error) or time.monotonic() >= deadline:
                break
            await asyncio.sleep(1.0)
        if last_error:
            console.print(f"[bold red]✖ Schema/topic bootstrap failed:[/bold red] {last_error}")
        await stack.close()
        return report

    report = asyncio.run(_wait_and_bootstrap())
    return stack, report


def stack_up(
    *,
    cluster: bool = False,
    port: int = 5180,
    host: str = "127.0.0.1",
    wait_seconds: int = 30,
    verify: bool = True,
    open_browser: bool = False,
    as_json: bool = False,
) -> dict[str, Any]:
    """Unified launcher for Standalone Web UI (`ucx up`) and Distributed Cluster + Web UI (`ucx up --cluster`)."""
    base_url = f"http://{host}:{port}"
    normalized_backend = "docker"

    if not cluster:
        # Scenario 1: Standalone Web UI + Chat Server
        fe_status = _detect_frontend_bundle()
        ollama_status = _probe_local_ollama()
        ui_status = _ensure_ui_daemon_running(
            host=host,
            port=port,
            cluster_mode=None,
            wait_seconds=float(wait_seconds),
        )
        components = (fe_status, ollama_status, ui_status)
        checks = _verify_ui_endpoints(host=host, port=port, cluster_mode=None) if verify else ()
        all_healthy = all(c.healthy for c in components) and all(chk.healthy for chk in checks)

        if open_browser and all_healthy:
            with contextlib.suppress(Exception):
                webbrowser.open(base_url)

        payload: dict[str, Any] = {
            "mode": "standalone",
            "backend": "standalone",
            "ui_url": base_url,
            "all_healthy": all_healthy,
            "components": [c.model_dump(mode="json") for c in components],
            "checks": [chk.model_dump(mode="json") for chk in checks],
        }
        if as_json:
            print(json.dumps(payload))
        else:
            console.print(
                _render_components_table(
                    components,
                    title="UClone-X Standalone Stack — Auto-Detected Components",
                )
            )
            if checks:
                console.print(
                    _render_verification_table(
                        checks,
                        backend="standalone",
                        title="Standalone Web UI & Chat Verification Suite",
                    )
                )
            console.print(
                Panel(
                    f"[bold green]✔ UClone-X Web UI & Chat Server Ready[/bold green]\n\n"
                    f"[bold]Web UI Chat:[/bold] [cyan]{base_url}[/cyan]\n"
                    f"[bold]Health API:[/bold]  [dim]{base_url}/api/health[/dim]\n"
                    f"[bold]Stop Stack:[/bold]  [yellow]./ucx ui down[/yellow]",
                    title="UClone-X Standalone Stack Active",
                    border_style="green" if all_healthy else "red",
                )
            )
        if not all_healthy:
            raise typer.Exit(code=1)
        return payload

    # Scenario 2: Distributed Cluster + Cluster-Backed Web UI
    stack, health_report = _start_and_bootstrap_docker_cluster(wait_seconds=wait_seconds)

    fe_status = _detect_frontend_bundle()
    ui_status = _ensure_ui_daemon_running(
        host=host,
        port=port,
        cluster_mode=normalized_backend,
        wait_seconds=float(wait_seconds),
    )
    all_components = (*health_report.components, fe_status, ui_status)

    checks_list: list[InfraComponentStatus] = []
    if verify:
        cluster_checks = asyncio.run(_verify_and_close(stack))
        ui_checks = _verify_ui_endpoints(
            host=host,
            port=port,
            cluster_mode=normalized_backend,
        )
        checks_list.extend(cluster_checks)
        checks_list.extend(ui_checks)

    checks_tuple = tuple(checks_list)
    all_healthy = (
        health_report.all_healthy
        and fe_status.healthy
        and ui_status.healthy
        and all(chk.healthy for chk in checks_tuple)
    )

    if open_browser and all_healthy:
        with contextlib.suppress(Exception):
            webbrowser.open(base_url)

    cluster_payload: dict[str, Any] = {
        "mode": "cluster",
        "backend": normalized_backend,
        "ui_url": base_url,
        "cluster_health_url": f"{base_url}/api/cluster/health",
        "all_healthy": all_healthy,
        "components": [c.model_dump(mode="json") for c in all_components],
        "checks": [chk.model_dump(mode="json") for chk in checks_tuple],
    }
    if as_json:
        print(json.dumps(cluster_payload))
    else:
        console.print(
            _render_components_table(
                all_components,
                title=f"UClone-X Cluster + Web UI Stack (backend={normalized_backend})",
            )
        )
        if checks_tuple:
            console.print(
                _render_verification_table(
                    checks_tuple,
                    backend=normalized_backend,
                    title=f"End-to-End Cluster + Web UI Verification Suite (backend={normalized_backend})",
                )
            )
        console.print(
            Panel(
                f"[bold green]✔ UClone-X Distributed Cluster + Web UI Ready[/bold green]\n\n"
                f"[bold]Web UI Chat:[/bold]        [cyan]{base_url}[/cyan]\n"
                f"[bold]Cluster Health API:[/bold] [cyan]{base_url}/api/cluster/health[/cyan]\n"
                f"[bold]Cluster Turn API:[/bold]   [dim]{base_url}/api/cluster/execute[/dim]\n"
                f"[bold]Stop Entire Stack:[/bold]  [yellow]./ucx cluster down[/yellow]",
                title="UClone-X Cluster Stack Active",
                border_style="green" if all_healthy else "red",
            )
        )
    if not all_healthy:
        raise typer.Exit(code=1)
    return cluster_payload


async def _verify_and_close(stack: ClusterRuntimeStack) -> tuple[InfraComponentStatus, ...]:
    try:
        return await stack.run_live_verification_suite()
    finally:
        await stack.close()


def _compose_down_command(volumes: bool) -> list[str]:
    """`stop` keeps data; `--volumes` removes this project's containers and volumes only."""
    if volumes:
        return _compose("down", "--volumes")
    return _compose("stop", *_DOCKER_SERVICES)


def _stop_managed_port(port: int) -> tuple[tuple[int, ...], str | None]:
    """Stop a recorded UClone-X daemon on `port` if running."""
    try:
        outcome = ui_process.stop_ui_server(port=port)
        return outcome.stopped_pids, None
    except (
        ListeningProcessLookupError,
        DashboardNotIdentifiedError,
        DashboardStopUnconfirmedError,
    ) as exc:
        return (), str(exc)


def stack_down(
    *,
    port: int = 5180,
    cluster: bool = True,
    volumes: bool = False,
    as_json: bool = False,
) -> dict[str, Any]:
    """Unified shutdown for the Web UI server, standalone cluster gateway, and Docker cluster services."""
    stopped_ui_pids, ui_warning = _stop_managed_port(port)
    gateway_pids: tuple[int, ...] = ()
    if port != _DEFAULT_CLUSTER_GATEWAY_PORT:
        with contextlib.suppress(Exception):
            if ui_process.read_dashboard_record(_DEFAULT_CLUSTER_GATEWAY_PORT) is not None:
                gateway_pids, _ = _stop_managed_port(_DEFAULT_CLUSTER_GATEWAY_PORT)

    docker_stopped = False
    if cluster:
        completed = subprocess.run(
            _compose_down_command(volumes), capture_output=True, text=True, check=False
        )
        docker_stopped = completed.returncode == 0

    payload: dict[str, Any] = {
        "port": port,
        "ui_stopped_pids": list(stopped_ui_pids),
        "gateway_stopped_pids": list(gateway_pids),
        "docker_cluster_stopped": docker_stopped,
        "volumes_removed": bool(cluster and volumes),
        "warning": ui_warning,
    }
    if as_json:
        print(json.dumps(payload))
        return payload

    if stopped_ui_pids:
        pids_str = ", ".join(map(str, stopped_ui_pids))
        console.print(
            f"[bold green]✔ Stopped Web UI & Chat server on port {port} (PID: {pids_str}).[/bold green]"
        )
    elif ui_warning:
        console.print(f"[yellow]⚠️ Port {port}: {ui_warning}[/yellow]")
    else:
        console.print(f"[dim]• No active Web UI daemon recorded on port {port}.[/dim]")

    if gateway_pids:
        gw_str = ", ".join(map(str, gateway_pids))
        console.print(
            f"[bold green]✔ Stopped Cluster HTTP gateway on port {_DEFAULT_CLUSTER_GATEWAY_PORT} (PID: {gw_str}).[/bold green]"
        )

    if cluster:
        if docker_stopped:
            console.print(
                "[bold green]✔ Stopped Docker cluster infrastructure services (kafka, postgres, valkey, centrifugo).[/bold green]"
            )
        else:
            console.print("[dim]• Docker cluster containers were not running or skipped.[/dim]")

    return payload


@cluster_app.command("up")
def cluster_up(
    with_ui: bool = typer.Option(
        True,
        "--with-ui/--no-ui",
        help="Launch the cluster-backed Web UI server alongside the cluster (default: True)",
    ),
    verify: bool = typer.Option(
        True,
        "--verify/--no-verify",
        help="Automatically verify all detected components after startup (default: True)",
    ),
    port: int = typer.Option(
        5180,
        "--port",
        "-p",
        help="Port for the cluster-backed Web UI & Chat server",
    ),
    host: str = typer.Option(
        "127.0.0.1",
        "--host",
        "-h",
        help="Host interface for the Web UI server",
    ),
    open_browser: bool = typer.Option(
        False,
        "--open/--no-open",
        help="Automatically open the Web UI in the default browser",
    ),
    wait_seconds: int = typer.Option(
        60,
        "--wait-seconds",
        help="Maximum seconds to poll cluster and UI services until healthy",
    ),
    as_json: bool = typer.Option(
        False,
        "--json",
        help="Output startup and verification report as JSON",
    ),
) -> None:
    """Start the distributed cluster stack + cluster-backed Web UI and verify all components."""
    if with_ui:
        stack_up(
            cluster=True,
            port=port,
            host=host,
            wait_seconds=wait_seconds,
            verify=verify,
            open_browser=open_browser,
            as_json=as_json,
        )
        return

    stack, report = _start_and_bootstrap_docker_cluster(wait_seconds=wait_seconds)
    checks: tuple[InfraComponentStatus, ...] = ()
    if verify:
        checks = asyncio.run(_verify_and_close(stack))

    if as_json:
        print(
            json.dumps(
                {
                    "backend": report.backend,
                    "all_healthy": report.all_healthy and all(c.healthy for c in checks),
                    "components": [c.model_dump(mode="json") for c in report.components],
                    "checks": [c.model_dump(mode="json") for c in checks],
                }
            )
        )
    else:
        console.print(_render_health_table(report, title="Docker Cluster Services"))
        if checks:
            console.print(_render_verification_table(checks, report.backend))

    if not report.all_healthy or not all(c.healthy for c in checks):
        raise typer.Exit(code=1)


@cluster_app.command("down")
def cluster_down(
    volumes: bool = typer.Option(
        False,
        "--volumes",
        "-v",
        help="Remove this stack's containers and volumes (its data) instead of only stopping them",
    ),
    with_ui: bool = typer.Option(
        True,
        "--with-ui/--no-ui",
        help="Also stop any running Web UI or Cluster Gateway background server (default: True)",
    ),
    port: int = typer.Option(
        5180,
        "--port",
        "-p",
        help="Port of the Web UI server to stop when --with-ui is enabled",
    ),
    as_json: bool = typer.Option(
        False,
        "--json",
        help="Output shutdown report as JSON",
    ),
) -> None:
    """Stop the distributed cluster stack (and cluster-backed Web UI server)."""
    if with_ui:
        stack_down(
            port=port,
            cluster=True,
            volumes=volumes,
            as_json=as_json,
        )
        return

    completed = subprocess.run(
        _compose_down_command(volumes), capture_output=True, text=True, check=False
    )
    if completed.returncode != 0:
        console.print(
            f"[bold red]✖ Failed to stop Docker cluster services:[/bold red]\n"
            f"{completed.stderr.strip() or completed.stdout.strip()}"
        )
        raise typer.Exit(code=1)

    if as_json:
        print(
            json.dumps(
                {
                    "port": port,
                    "ui_stopped_pids": [],
                    "gateway_stopped_pids": [],
                    "docker_cluster_stopped": True,
                    "volumes_removed": volumes,
                    "warning": None,
                }
            )
        )
    else:
        console.print("[bold green]✔ Stopped Docker cluster infrastructure services.[/bold green]")


