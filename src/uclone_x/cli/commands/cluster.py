@cluster_app.command("run")
def cluster_run(
    prompt: str = typer.Argument(
        ...,
        help="User prompt to execute on the distributed cluster runtime",
    ),
    session_id: str = typer.Option(
        "sess-cli",
        "--session-id",
        help="Session identifier for partitioned routing and state persistence",
    ),
    agent_id: str = typer.Option(
        "default",
        "--agent-id",
        help="Agent identifier to execute the turn",
    ),
    workers: int = typer.Option(
        2,
        "--workers",
        help="Number of stateless worker instances in the pool",
    ),
    as_json: bool = typer.Option(
        False,
        "--json",
        help="Output turn execution result as JSON",
    ),
) -> None:
    """Run one turn on a worker in this process; its SSE crosses Kafka to Centrifugo.

    The turn runs on the configured model. `ucx worker` is what consumes turns from Kafka.
    """
    stack = _build_stack(num_workers=workers)

    async def _exec() -> Any:
        try:
            await stack.bootstrap_schema()
            return await stack.execute_turn_end_to_end(
                prompt=prompt,
                session_id=session_id,
                agent_id=agent_id,
            )
        finally:
            await stack.close()

    result = asyncio.run(_exec())
    if as_json:
        print(json.dumps(result.model_dump(mode="json")))
        return

    budget_str = (
        f"{result.budget_snapshot.total_consumed_tokens} tokens "
        f"(turns={result.budget_snapshot.turn_count})"
        if result.budget_snapshot is not None
        else "n/a"
    )
    seqs = [str(env.data.get("seq", "?")) for env in result.sse_events]
    console.print(
        Panel(
            f"[bold]Session:[/bold] {result.session_id}\n"
            f"[bold]Turn ID:[/bold] {result.turn_id}\n"
            f"[bold]Worker:[/bold] [cyan]{result.worker_id}[/cyan]\n"
            f"[bold]Outcome:[/bold] {result.disposition}\n"
            f"[bold]Revision:[/bold] {result.committed_revision}\n"
            f"[bold]SSE Sequences:[/bold] {', '.join(seqs) or 'none'}\n"
            f"[bold]Token Budget:[/bold] {budget_str}\n\n"
            f"[bold green]{result.assistant_text}[/bold green]",
            title="Distributed Cluster Turn Result",
            border_style="cyan",
        )
    )


@cluster_app.command("serve")
def cluster_serve(
    host: str = typer.Option("127.0.0.1", "--host", help="Host interface to bind"),
    port: int = typer.Option(5190, "--port", help="TCP port to bind"),
    workers: int = typer.Option(2, "--workers", help="Number of stateless workers"),
) -> None:
    """Start the FastAPI cluster HTTP gateway server."""
    try:
        import uvicorn
    except ImportError as exc:
        from uclone_x.errors import MissingDependencyError

        raise MissingDependencyError(
            extra="http",
            package="uvicorn",
            feature="Cluster HTTP gateway (ucx cluster serve)",
        ) from exc

    stack = _build_stack(num_workers=workers)

    async def _bootstrap() -> None:
        try:
            await stack.bootstrap_schema()
        finally:
            await stack.close()

    asyncio.run(_bootstrap())
    http_app = create_cluster_http_app(stack)
    record, _ = ui_process.new_dashboard_record(port=port, host=host)
    with contextlib.suppress(DashboardNotIdentifiedError):
        ui_process.write_dashboard_record(record)
    try:
        uvicorn.run(http_app, host=host, port=port)
    finally:
        ui_process.remove_dashboard_record(record)
