def _compose_file() -> Path:
    """`$UCX_CLUSTER_COMPOSE_FILE`, else `docker-compose.yml` in the working directory."""
    override = os.environ.get(_COMPOSE_FILE_VAR, "").strip()
    path = Path(override).expanduser() if override else Path.cwd() / "docker-compose.yml"
    if not path.is_file():
        raise ClusterConfigError(
            f"No cluster compose file at {path}. Run from the repository root or set "
            f"{_COMPOSE_FILE_VAR}."
        )
    return path.resolve()


def _stack_env_file() -> Path:
    return stack_env_path(_compose_file().parent)


def ensure_stack_env(path: Path) -> tuple[str, ...]:
    """Generate every missing stack secret into `path` once; return the names generated.

    Existing values are never rewritten, so a running stack keeps its passwords. The file is
    created with mode 0600 inside a 0700 directory.
    """
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    current = read_stack_env(path) if path.is_file() else {}
    generated = tuple(name for name in REQUIRED_STACK_SECRETS if not current.get(name))
    if not generated:
        return ()
    for name in generated:
        current[name] = secrets.token_hex(32)
    body = "".join(f"{key}={value}\n" for key, value in current.items())
    tmp = path.with_suffix(".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(
            "# Generated by `ucx cluster up`. Secrets for this stack only; never commit.\n"
        )
        handle.write(body)
    os.replace(tmp, path)
    return generated


def _compose(*args: str) -> list[str]:
    return [
        "docker",
        "compose",
        "-f",
        str(_compose_file()),
        "--env-file",
        str(_stack_env_file()),
        *args,
    ]


